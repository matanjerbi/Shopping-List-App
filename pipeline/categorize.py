_STRIP = re.compile(r"[\"'`׳״\-–_.,/\\()\[\]{}*+!?:;|]")


def normalize(name: str) -> str:
    t = (name or "").replace("׳", "'").replace("״", '"')
    t = re.sub(r"\s+", " ", t).strip()
    return " " + t + " "


def _norm_phrase(p: str) -> str:
    return p.replace("׳", "'").replace("״", '"')


_COMPILED = [
    (cid, label, [_norm_phrase(p) for p in inc], [_norm_phrase(p) for p in exc])
    for cid, label, inc, exc in RULES
]

LABELS = {cid: label for cid, label, _, _ in RULES}


def categorize(name: str) -> str:
    n = normalize(name)
    for cid, _label, inc, exc in _COMPILED:
        if any(p in n for p in inc) and not any(p in n for p in exc):
            return cid
    return ""
